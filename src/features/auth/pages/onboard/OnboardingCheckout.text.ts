/** Arabic month count with the right plural form ("3 أشهر", "12 شهرًا"). */
function arabicMonths(n: number): string {
  if (n === 1) return 'شهر واحد';
  if (n === 2) return 'شهران';
  if (n >= 3 && n <= 10) return `${n} أشهر`;
  return `${n} شهرًا`;
}

/**
 * "$10" kept left to right inside Arabic text: without the isolation marks the bidi algorithm turns the
 * digits after Arabic letters into Arabic numbers and the dollar sign lands on the wrong side ("10$").
 */
function usd(amount: number | string): string {
  return `\u2066$${amount}\u2069`;
}

